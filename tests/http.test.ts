import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { request as httpRequest } from 'node:http';
import { createApp } from '../server/index.ts';
test('API locale : import → qualification → export filtré, Host/Origin et restauration protégés',async t=>{
  const dir=mkdtempSync(join(tmpdir(),'tva-http-'));
  const {app,stores}=createApp(dir,0);
  const server=app.listen(0,'127.0.0.1');
  await new Promise<void>(resolve=>server.once('listening',resolve));
  const address=server.address();assert.ok(address&&typeof address!=='string');
  t.after(async()=>{await new Promise<void>(resolve=>server.close(()=>resolve()));Object.values(stores).forEach(s=>s.close());rmSync(dir,{recursive:true,force:true});});
  const base='http://127.0.0.1:'+address.port;
  const headers={'Host':'127.0.0.1:'+address.port,'Origin':base,'X-TVA-Client':'1','Content-Type':'application/json'};
  const send=(path:string,body:unknown)=>fetch(base+path,{method:'POST',headers,body:JSON.stringify(body)});
  const hostile=await new Promise<number>(resolve=>{httpRequest(base+'/api/state',{headers:{Host:'evil.test'}},res=>{res.resume();resolve(res.statusCode!);}).end();});
  assert.equal(hostile,403);
  assert.equal((await fetch(base+'/api/undo',{method:'POST',headers:{...headers,Origin:'https://evil.test'},body:'{}'})).status,403);
  assert.equal((await fetch(base+'/api/undo',{method:'POST',headers:{Host:headers.Host,'Content-Type':'application/json'},body:'{}'})).status,403);
  const csv={filename:'fictif.csv',account:'A',base64:Buffer.from('Date;Libellé;Montant\n01/01/2026;=SUM(1);120,00\n02/02/2026;Autre;60,00').toString('base64')};
  assert.equal((await send('/api/import',{...csv,selectedLines:[2,3],acceptRejected:false,confirmDuplicates:false})).status,200);
  const state=await (await fetch(base+'/api/state',{headers})).json();
  assert.equal(state.operations.length,2);assert.equal(state.operations[0].status,'pending');
  assert.equal((await send('/api/settings',{regime:'receipts',regimeConfirmed:true,rates:[2000]})).status,200);
  const o=state.operations[0];const update={id:o.id,revision:o.revision,status:'confirmed',parts:o.parts.map((p:object)=>({...p,nature:'revenue',treatment:'taxable',periodConfirmed:true}))};
  assert.equal((await send('/api/operations',[update])).status,200);
  assert.equal((await send('/api/operations',[update])).status,409);
  const key=JSON.stringify(['2026-01-01','2026-01-31','']);
  assert.equal((await send('/api/settlement',{key,value:{adjustmentsCents:100,priorCreditCents:50,confirmed:true}})).status,200);
  const response=await fetch(base+'/api/export?from=2026-01-01&to=2026-01-31',{headers});
  const exported=await response.text();assert.equal(response.status,200);
  assert.match(exported,/'=SUM\(1\)/);assert.doesNotMatch(exported,/"Autre"/);assert.match(exported,/"Solde de préparation";"2050"/);
  const filtered=await (await fetch(base+'/api/export?from=2026-01-01&to=2026-01-31&status=confirmed',{headers})).text();
  assert.match(filtered,/"Solde de préparation";"2000"/);
  const backup=await (await fetch(base+'/api/backup',{headers})).json();
  assert.equal((await send('/api/restore',{confirmation:'NON',backup})).status,400);
  assert.equal((await send('/api/restore',{confirmation:'RESTAURER',backup})).status,200);
  assert.equal((await fetch(base+'/api/source/'+state.operations[0].importId,{headers})).status,200);
});
