import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';

test('TVA trimestrielle : PDF débordant de la période, T1 à T4, année, export et conservation des autres mouvements',async({page})=>{
  await page.goto('/');
  await page.getByLabel('Raccourci de période',{exact:true}).selectOption('quarter');
  await page.getByLabel('Année du trimestre TVA',{exact:true}).selectOption('2026');
  await page.getByLabel('Trimestre TVA',{exact:true}).selectOption('2');
  await expect(page.getByLabel('Date TVA de début',{exact:true})).toHaveValue('2026-04-01');
  await expect(page.getByLabel('Date TVA de fin',{exact:true})).toHaveValue('2026-06-30');
  await page.getByRole('button',{name:'Importer des relevés PDF',exact:false}).click();
  await page.getByLabel('Compte bancaire PDF',{exact:true}).fill('Trimestre navigateur');
  await page.getByLabel('Relevé PDF',{exact:true}).setInputFiles('examples/releve-fictif-trimestres.pdf');
  await page.getByRole('button',{name:'Lire le PDF',exact:true}).click();
  await expect(page.getByText('4 mouvements possibles',{exact:true})).toBeVisible();
  await expect(page.getByLabel('Début du relevé PDF',{exact:true})).toHaveValue('2026-03-15');
  await expect(page.getByLabel('Fin du relevé PDF',{exact:true})).toHaveValue('2026-07-15');
  await page.getByLabel('J’ai comparé les lignes sélectionnées',{exact:false}).check();
  await page.getByRole('button',{name:'Importer 4 mouvements PDF',exact:true}).click();
  await page.getByRole('combobox',{name:'Compte',exact:true}).selectOption('Trimestre navigateur');
  await expect(page.getByRole('button',{name:'Honoraires avril',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Honoraires juin',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Hors trimestre avant',exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Hors trimestre après',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Paramètres',exact:true}).click();
  await page.getByLabel('Régime vérifié').selectOption('receipts');
  await page.getByLabel('J’ai vérifié ce régime',{exact:false}).check();
  await page.getByRole('button',{name:'Enregistrer les paramètres',exact:true}).click();
  await page.getByRole('button',{name:'Fermer la fenêtre',exact:true}).click();
  for(const label of ['Honoraires avril','Honoraires juin']) {
    await page.getByRole('button',{name:label,exact:true}).click();
    await page.getByLabel('Nature',{exact:true}).selectOption('revenue');
    await page.getByLabel('Traitement TVA',{exact:true}).selectOption('taxable');
    await page.getByLabel('Je confirme la date retenue',{exact:false}).check();
    await page.getByRole('button',{name:'Confirmer l’opération',exact:true}).click();
  }
  await expect(page.locator('.metric').first().locator('strong')).toHaveText('100,00 €');
  await page.screenshot({path:'test-results/trimestre-t2.png',fullPage:true});
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('link',{name:'Exporter la vue en CSV',exact:true}).click();
  const download=await downloadPromise,csv=await readFile((await download.path())!,'utf8');
  expect(csv).toContain('Honoraires avril');expect(csv).toContain('Honoraires juin');expect(csv).not.toContain('Hors trimestre');
  expect(csv).toContain('"TVA collectée confirmée";"10000"');
  await page.getByLabel('Trimestre TVA',{exact:true}).selectOption('1');
  await expect(page.getByRole('button',{name:'Hors trimestre avant',exact:true})).toBeVisible();
  await page.getByLabel('Trimestre TVA',{exact:true}).selectOption('3');
  await expect(page.getByRole('button',{name:'Hors trimestre après',exact:true})).toBeVisible();
  await page.getByLabel('Trimestre TVA',{exact:true}).selectOption('4');
  await expect(page.getByLabel('Date TVA de fin',{exact:true})).toHaveValue('2026-12-31');
  await page.getByLabel('Trimestre TVA',{exact:true}).selectOption('2');
  await page.getByLabel('Année du trimestre TVA',{exact:true}).selectOption('2025');
  await expect(page.getByText('Aucun résultat pour ces filtres',{exact:true})).toBeVisible();
  await page.getByLabel('Année du trimestre TVA',{exact:true}).selectOption('2026');
  await page.getByLabel('Date TVA de début',{exact:true}).fill('2026-04-15');
  await expect(page.getByLabel('Raccourci de période',{exact:true})).toHaveValue('custom');
  await expect(page.locator('.metric').first().locator('strong')).toHaveText('60,00 €');
  await page.getByLabel('Raccourci de période',{exact:true}).selectOption('all');
  for(const name of ['Hors trimestre avant','Honoraires avril','Honoraires juin','Hors trimestre après'])await expect(page.getByRole('button',{name,exact:true})).toBeVisible();
  const state=await (await page.request.get('/api/state')).json();
  expect(state.operations.filter((o:{account:string})=>o.account==='Trimestre navigateur')).toHaveLength(4);
});
