import { test,expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
test('PDF texte : choix du fichier, deux pages, correction, contrôle, import, original et sauvegarde',async({page})=>{
  const errors:string[]=[],external:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',req=>{if(!req.url().startsWith('http://127.0.0.1:3217')&&!req.url().startsWith('data:'))external.push(req.url());});
  await page.goto('/');
  await page.getByRole('button',{name:'Importer des relevés PDF',exact:false}).click();
  await page.getByLabel('Compte bancaire PDF',{exact:true}).fill('PDF navigateur');
  await page.getByLabel('Relevé PDF',{exact:true}).setInputFiles('examples/releve-fictif-sg.pdf');
  await page.getByRole('button',{name:'Lire le PDF',exact:true}).click();
  await expect(page.getByText('9 mouvements possibles',{exact:true})).toBeVisible();
  await expect(page.getByText('2 page(s) lue(s)',{exact:true})).toBeVisible();
  await expect(page.getByRole('img',{name:'Page 1 du relevé bancaire original',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Importer 8 mouvements PDF',exact:true})).toBeDisabled();
  await page.getByRole('textbox',{name:/^Libellé mouvement PDF /}).first().fill('Honoraires PDF corrigés');
  await page.getByRole('button',{name:'Actualiser l’aperçu PDF et les corrections',exact:true}).click();
  await expect(page.getByRole('textbox',{name:/^Libellé mouvement PDF /}).first()).toHaveValue('Honoraires PDF corrigés');
  await page.getByLabel('Page du PDF',{exact:true}).selectOption('2');
  await expect(page.getByRole('img',{name:'Page 2 du relevé bancaire original',exact:true})).toBeVisible();
  await page.getByRole('dialog').screenshot({path:'test-results/import-pdf.png'});
  await page.getByLabel('J’ai comparé les lignes sélectionnées',{exact:false}).check();
  await page.getByRole('button',{name:'Importer 8 mouvements PDF',exact:true}).click();
  await expect(page.getByText('8 mouvements PDF importés, en attente de qualification.',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Honoraires PDF corrigés',exact:true}).click();
  await expect(page.getByRole('dialog').locator('.editor-intro')).toContainText('Page 1 · ligne');
  await page.getByText('Provenance bancaire et données d’origine',{exact:true}).click();
  const sourceDownload=page.waitForEvent('download');
  await page.getByRole('link',{name:'Télécharger le document original',exact:true}).click();
  const source=await sourceDownload;
  const sourcePath=await source.path();
  expect(source.suggestedFilename()).toMatch(/\.pdf$/);
  expect(await readFile(sourcePath!)).toEqual(await readFile('examples/releve-fictif-sg.pdf'));
  await page.getByRole('button',{name:'Fermer la fenêtre',exact:true}).click();
  await page.reload();await expect(page.getByRole('button',{name:'Honoraires PDF corrigés',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Sauvegarder / restaurer',exact:true}).click();
  const backupDownload=page.waitForEvent('download');
  await page.getByRole('link',{name:'Télécharger la sauvegarde complète',exact:true}).click();
  const backup=await backupDownload,backupPath=await backup.path();
  const payload=JSON.parse(await readFile(backupPath!,'utf8'));
  const record=payload.payload.imports.find((i:{format:string;account:string})=>i.format==='pdf'&&i.account==='PDF navigateur');
  expect(record.pdf.pageCount).toBe(2);expect(record.base64).toBe((await readFile('examples/releve-fictif-sg.pdf')).toString('base64'));
  await page.getByLabel('Fichier de sauvegarde',{exact:true}).setInputFiles(backupPath!);
  await page.getByLabel('Pour remplacer l’espace actuel, saisissez RESTAURER',{exact:true}).fill('RESTAURER');
  await page.getByRole('button',{name:'Restaurer et remplacer cet espace',exact:true}).click();
  await expect(page.getByText('Sauvegarde restaurée.',{exact:false})).toBeVisible();
  await expect(page.getByRole('button',{name:'Honoraires PDF corrigés',exact:true})).toBeVisible();
  expect(errors).toEqual([]);expect(external).toEqual([]);
});
test('PDF scanné : OCR local exécuté, avertissement, trois mouvements et refus d’un PDF déjà importé',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'Importer des relevés PDF',exact:false}).click();
  await page.getByLabel('Compte bancaire PDF',{exact:true}).fill('Scan navigateur');
  await page.getByLabel('Relevé PDF',{exact:true}).setInputFiles('examples/releve-fictif-scan.pdf');
  await page.getByRole('button',{name:'Lire le PDF',exact:true}).click();
  await expect(page.getByText('3 mouvements possibles',{exact:true})).toBeVisible();
  await expect(page.getByText('OCR local utilisé',{exact:true})).toBeVisible();
  await expect(page.getByText('Page 1 lue par OCR local',{exact:false})).toBeVisible();
  await page.getByLabel('J’ai comparé les lignes sélectionnées',{exact:false}).check();
  await page.getByRole('button',{name:'Importer 3 mouvements PDF',exact:true}).click();
  await expect(page.getByText('3 mouvements PDF importés, en attente de qualification.',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Importer des relevés PDF',exact:false}).click();
  await page.getByLabel('Compte bancaire PDF',{exact:true}).fill('Scan navigateur');
  await page.getByLabel('Relevé PDF',{exact:true}).setInputFiles('examples/releve-fictif-scan.pdf');
  await page.getByRole('button',{name:'Lire le PDF',exact:true}).click();
  await expect(page.getByText('Ce PDF a déjà été importé pour ce compte.',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Importer 0 mouvements PDF',exact:true})).toBeDisabled();
});
