import { test,expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
test('Parcours réel dans le navigateur : CSV, qualification, dépenses, ventilation, sauvegarde et restauration',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const external:string[]=[];page.on('request',req=>{if(!req.url().startsWith('http://127.0.0.1:3217')&&!req.url().startsWith('data:'))external.push(req.url());});
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Préparer ma TVA'})).toBeVisible();
  await page.getByRole('button',{name:'Importer un relevé CSV',exact:false}).click();
  await page.getByRole('dialog').getByRole('combobox',{name:'Compte bancaire',exact:true}).fill('Compte principal');
  await page.getByLabel('Relevé CSV',{exact:true}).setInputFiles('examples/releve-fictif.csv');
  await page.getByRole('button',{name:'Analyser le CSV',exact:true}).click();
  await expect(page.getByText('1 doublon(s) potentiel(s)',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Importer 8 opérations',exact:true}).click();
  await expect(page.getByText('8 opérations importées, en attente de qualification.',{exact:true})).toBeVisible();
  await page.getByRole('combobox',{name:'Compte',exact:true}).selectOption('Compte principal');
  await page.getByRole('button',{name:'Paramètres',exact:true}).click();
  await page.getByLabel('Régime vérifié').selectOption('receipts');
  await page.getByLabel('J’ai vérifié ce régime', {exact:false}).check();
  await page.getByRole('button',{name:'Enregistrer les paramètres',exact:true}).click();
  await page.getByRole('button',{name:'Fermer la fenêtre',exact:true}).click();
  await page.getByRole('button',{name:'Honoraires dossier ALPHA',exact:true}).click();
  await page.getByLabel('Nature',{exact:true}).selectOption('revenue');
  await page.getByLabel('Traitement TVA',{exact:true}).selectOption('taxable');
  await page.getByLabel('Je confirme la date retenue',{exact:false}).check();
  await page.getByRole('button',{name:'Confirmer l’opération',exact:true}).click();
  await expect(page.locator('.metric').nth(0).locator('strong')).toHaveText('200,00 €');
  await page.getByRole('button',{name:'Fournitures bureau',exact:true}).click();
  await page.getByLabel('Nature',{exact:true}).selectOption('expense');
  await page.getByLabel('Traitement TVA',{exact:true}).selectOption('taxable');
  await page.getByLabel('Déduction',{exact:true}).selectOption('10000');
  await page.getByLabel('Coefficient 1',{exact:true}).fill('9999999999,99');
  await expect(page.getByLabel('Coefficient 1',{exact:true})).toBeVisible();
  await page.getByLabel('Coefficient 1',{exact:true}).fill('100,00');
  await page.getByLabel('HT facturé 1',{exact:true}).fill('100,00');
  await page.getByLabel('TVA facturée 1',{exact:true}).fill('20,00');
  await page.getByLabel('J’ai vérifié le HT',{exact:false}).check();
  await page.getByLabel('Je confirme le droit à déduction',{exact:false}).check();
  await page.getByLabel('Je confirme la date retenue',{exact:false}).check();
  await page.getByRole('button',{name:'Confirmer l’opération',exact:true}).click();
  await expect(page.locator('.metric').nth(1).locator('strong')).toHaveText('20,00 €');
  await page.getByRole('button',{name:'Dépense mixte à ventiler',exact:true}).click();
  await page.getByRole('button',{name:'Ajouter une ventilation',exact:false}).click();
  await page.getByLabel('TTC ventilation 1',{exact:true}).fill('-120,00');
  await page.getByLabel('TTC ventilation 2',{exact:true}).fill('-60,00');
  await page.getByRole('button',{name:'Enregistrer à vérifier',exact:true}).click();
  await expect(page.getByText('2 ventilations',{exact:false})).toBeVisible();
  await page.reload();
  await expect(page.locator('.metric').nth(2).locator('strong')).toHaveText('180,00 €');
  await page.getByRole('button',{name:'Sauvegarder / restaurer',exact:true}).click();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('link',{name:'Télécharger la sauvegarde complète',exact:true}).click();
  const download=await downloadPromise;
  const path=await download.path();expect(path).not.toBeNull();
  const backup=JSON.parse(await readFile(path!,'utf8'));
  expect(backup.payload.operations.filter((operation:{account:string})=>operation.account==='Compte principal')).toHaveLength(8);
  await page.getByLabel('Fichier de sauvegarde',{exact:true}).setInputFiles(path!);
  await page.getByLabel('Pour remplacer l’espace actuel, saisissez RESTAURER',{exact:true}).fill('RESTAURER');
  await page.getByRole('button',{name:'Restaurer et remplacer cet espace',exact:true}).click();
  await expect(page.getByText('Sauvegarde restaurée.',{exact:false})).toBeVisible();
  await expect(page.locator('.metric').nth(2).locator('strong')).toHaveText('180,00 €');
  const exportPromise=page.waitForEvent('download');
  await page.getByRole('link',{name:'Exporter la vue en CSV',exact:true}).click();
  const csv=await exportPromise;expect(csv.suggestedFilename()).toBe('tva-cabinet-export.csv');
  await page.screenshot({path:'test-results/parcours-principal.png',fullPage:true});
  expect(external).toEqual([]);expect(errors).toEqual([]);
});
test('Aperçu CSV modifiable : une correction explicite doit être réanalysée puis conservée',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'Importer un relevé CSV',exact:false}).click();
  await page.getByRole('dialog').getByRole('combobox',{name:'Compte bancaire',exact:true}).fill('Test corrections');
  await page.getByLabel('Relevé CSV',{exact:true}).setInputFiles({name:'correction.csv',mimeType:'text/csv',buffer:Buffer.from('Date;Libellé;Montant\n31/02/2026;Correction fictive;10,00')});
  await page.getByRole('button',{name:'Analyser le CSV',exact:true}).click();
  await page.getByLabel('Date ligne 2',{exact:true}).fill('2026-02-28');
  await page.getByLabel('Montant ligne 2',{exact:true}).fill('12.01');
  await page.getByRole('button',{name:'Actualiser l’aperçu et les corrections',exact:true}).click();
  await page.getByRole('button',{name:'Importer 1 opérations',exact:true}).click();
  await expect(page.getByRole('button',{name:'Correction fictive',exact:true})).toBeVisible();
  await expect(page.getByRole('row').filter({has:page.getByRole('button',{name:'Correction fictive',exact:true})})).toContainText('12,01 €');
});
